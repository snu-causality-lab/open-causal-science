#!/usr/bin/env python3
"""Build the topic index from the individual paper records."""

import argparse
import re
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

DOCS = Path(__file__).resolve().parents[1] / "docs"
PAPERS = DOCS / "papers"
INDEX = DOCS / "paper-checks.md"
METADATA = re.compile(r"<!-- (topic|index-anchor|topic-anchor): (.+) -->")
FINDING_LABELS = ("Verified counterexample", "Author correction", "Verified discrepancy")
FINDING = re.compile(
    r"^> \*\*(.+?)\*\* · \[([^\[\]]+)\]\(#([\w-]+)\) · (.+)$"
)


@dataclass(frozen=True)
class Finding:
    label: str
    statement: str
    anchor: str
    summary: str


@dataclass(frozen=True)
class Paper:
    slug: str
    title: str
    topic: str
    index_anchors: tuple[str, ...]
    topic_anchors: tuple[str, ...]
    findings: tuple[Finding, ...]


def read_findings(record: Path, body: str) -> tuple[Finding, ...]:
    headings = re.findall(r"^#{2,6} (.+)$", body, re.M)
    anchors = {re.sub(r"[^\w -]", "", title.lower().strip()).replace(" ", "-")
               for title in headings}
    anchors.update(re.findall(r'<a (?:name|id)="([\w-]+)"></a>', body))
    findings = []
    finding_prefixes = tuple(f"> **{label}**" for label in FINDING_LABELS)
    for line in body.splitlines():
        if not line.startswith(finding_prefixes):
            continue
        match = FINDING.fullmatch(line)
        if not match:
            raise ValueError(f"{record.name}: expected a statement link and a summary in the finding")
        finding = Finding(*match.groups())
        if finding.anchor not in anchors:
            raise ValueError(f"{record.name}: finding links to missing section #{finding.anchor}")
        findings.append(finding)
    return tuple(findings)


def read_paper(record: Path) -> Paper:
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", record.stem):
        raise ValueError(f"{record.name}: expected a lowercase, hyphen-separated filename")

    title_line, _, rest = record.read_text(encoding="utf-8").partition("\n")
    if not title_line.startswith("# ") or not title_line[2:].strip():
        raise ValueError(f"{record.name}: start with a level-one heading")

    metadata: dict[str, list[str]] = defaultdict(list)
    for line in rest.lstrip("\n").splitlines():
        match = METADATA.fullmatch(line)
        if match is None:
            break
        key, value = match.groups()
        if key != "topic" and not re.fullmatch(r"[\w-]+", value):
            raise ValueError(f"{record.name}: invalid anchor {value!r}")
        metadata[key].append(value)

    if len(metadata["topic"]) != 1:
        raise ValueError(f"{record.name}: expected exactly one topic comment after the title")
    return Paper(record.stem, title_line[2:].strip(), metadata["topic"][0],
                 tuple(metadata["index-anchor"]), tuple(metadata["topic-anchor"]),
                 read_findings(record, rest))


def anchors_html(anchors: tuple[str, ...]) -> str:
    return "".join(f'<a name="{anchor}"></a>' for anchor in anchors)


def escape_link_label(label: str) -> str:
    return re.sub(r"([\\\[\]])", r"\\\1", label)


def render_findings(papers: list[Paper]) -> list[str]:
    entries = [(paper, finding) for paper in papers for finding in paper.findings]
    if not entries:
        return []
    lines = ["## Corrections and counterexamples", "",
             "| Published statement | Finding |", "| --- | --- |"]
    entries.sort(key=lambda entry: (FINDING_LABELS.index(entry[1].label), entry[0].title.casefold()))
    for paper, finding in entries:
        authors_year, separator, _ = paper.title.partition("), ")
        short_title = authors_year + ")" if separator else paper.title
        statement = escape_link_label(f"{short_title} · {finding.statement}").replace("|", r"\|")
        summary = finding.summary.replace("|", r"\|")
        target = f"papers/{paper.slug}.md#{finding.anchor}"
        lines.append(f"| [{statement}]({target}) | **{finding.label}** · {summary} |")
    return [*lines, ""]


def render_index(papers: list[Paper]) -> str:
    if not papers:
        raise ValueError("No paper records in docs/papers")
    by_topic: dict[str, list[Paper]] = defaultdict(list)
    used_anchors: set[str] = set()
    for paper in papers:
        by_topic[paper.topic].append(paper)
        for anchor in paper.index_anchors + paper.topic_anchors:
            if anchor in used_anchors:
                raise ValueError(f"Duplicate index anchor: {anchor}")
            used_anchors.add(anchor)

    lines = [
        "# Lean companions to published research",
        "",
        "<!-- Generated by scripts/build-paper-index.py from docs/papers/. -->",
        "",
        "We develop these formalizations to reuse results from the causal graph literature. Each companion credits the original paper and identifies the statement, assumptions, and Lean declaration or executable example.",
        "",
        "[Browse by topic](#browse-by-topic) · [Homepage correction reviews](errata.md)",
        "",
    ]
    lines.extend(render_findings(papers))
    lines.extend(['<a name="browse-by-topic"></a>', ""])
    for topic, group in sorted(by_topic.items(), key=lambda item: item[0].casefold()):
        topic_anchors = tuple(anchor for paper in group for anchor in paper.topic_anchors)
        if topic_anchors:
            lines.extend([anchors_html(topic_anchors), ""])
        lines.extend([f"## {topic}", ""])
        for paper in sorted(group, key=lambda item: (item.title.casefold(), item.slug)):
            title = escape_link_label(paper.title)
            lines.append(f"- {anchors_html(paper.index_anchors)}[{title}](papers/{paper.slug}.md)")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check the index without writing it")
    args = parser.parse_args()
    try:
        papers = [read_paper(record) for record in sorted(PAPERS.glob("*.md"))]
        expected = render_index(papers)
        if args.check:
            if not INDEX.is_file() or INDEX.read_text(encoding="utf-8") != expected:
                print("Paper index is stale. Run python3 scripts/build-paper-index.py.", file=sys.stderr)
                return 1
        else:
            INDEX.write_text(expected, encoding="utf-8")
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
